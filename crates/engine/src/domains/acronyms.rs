pub fn handle(q: &Query) -> Option<Answer> {
    let raw = q.raw.trim().trim_end_matches(['?', '.']).trim();
    let m = re!(r"(?i)^(?:(?:acronyms?|abbreviations?|initialisms?)\s+(?:for\s+|of\s+)?([A-Za-z.&]+)|what\s+(?:does|do)\s+(?:the\s+)?([A-Za-z.&]+)\s+(?:stand for|mean)|([A-Za-z.&]+)\s+(?:stands for|acronym|abbreviation|meaning|full form)|(?:full form|meaning|expansion)\s+of\s+([A-Za-z.&]+))$").captures(raw)?;
    let a = m.get(1).or(m.get(2)).or(m.get(3)).or(m.get(4))?.as_str();
    let key = a.replace('.', "").to_uppercase();
    // "meaning of life", "what does love mean": only all-caps words or explicit acronym requests
    let explicit = m.get(1).is_some() || raw.to_lowercase().contains("stand") || raw.to_lowercase().contains("full form");
    if !explicit && a.chars().any(|c| c.is_lowercase()) {
        return None;
    }
    let (k, exp) = ACRONYMS.iter().find(|(k, _)| *k == key)?;
    let list: Vec<&str> = exp.split("; ").collect();
    let mut pods = vec![
        pod("Input", "Input interpretation", text(format!("{k} (acronym)"))),
        primary(pod("Result", if list.len() > 1 { "Most common expansion" } else { "Expansion" }, text(list[0]))),
    ];
    if list.len() > 1 {
        pods.push(pod("Other", "Other expansions", text(list[1..].join(" | "))));
    }
    Some(Answer::new(format!("{k} (acronym)"), pods))
}
